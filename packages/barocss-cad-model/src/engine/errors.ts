/** A bracketed refusal code in a kernel message: `[RADIUS_EXCEEDS_FACE]`. */
const CODE = /\[([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)\]/g, FIRST_CODE = /\[([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)\]/;
function matches(rule: (typeof rules)[number], codes: ReadonlySet<string>, message: string): boolean {
  const c = rule.code;
  if (c !== undefined && (typeof c === 'string' ? codes.has(c) : c.some(x => codes.has(x)))) return true;
  return rule.text !== undefined && rule.text.test(message);
}
/**
 * A kernel refusal as a designer can act on it; `kind`, the thrown error's own code, kept when the message has no
 * bracketed one. The title and hint are as before; `detail` starts with the bracketed code when there is one.
 */
export function friendly(message: string, kind?: string): FriendlyError {
  let detail = message.replace(/^n\d+:\s*/, '').trim();
  const codes = new Set<string>();
  for (const m of message.matchAll(CODE)) codes.add(m[1]);
  const bracketed = FIRST_CODE.exec(detail)?.[1], code = bracketed ?? kind;
  if (bracketed && !detail.startsWith(`[${bracketed}]`)) detail = `[${bracketed}] ${detail.replace(`[${bracketed}] `, '').replace(`[${bracketed}]`, '').trim()}`;
  const extra = code ? { code } : {};
  if (code === 'BUTT_ON_OPEN_SIDE') {
    // Only the kernel's exact location prefix identifies members; never infer a joint from prose.
    const match = /^\[BUTT_ON_OPEN_SIDE\] point (0|[1-9]\d*): member (0|[1-9]\d*) meets member (0|[1-9]\d*): its end spans /.exec(detail);
    const indices = match?.slice(1).map(Number);
    const location = indices?.every(index => Number.isSafeInteger(index) && index < Number.MAX_SAFE_INTEGER)
      ? `At Point ${indices[0] + 1}, member ${indices[1] + 1} meets member ${indices[2] + 1}. ` : '';
    return { title: 'Butt joint would leave a gap',
      hint: `${location}The end does not fully meet material on the through member. For a T-joint, try T-joints → Cope; otherwise change this joint or section. Check the resulting preview before applying.`,
      detail, ...extra };
  }
  if (code === 'GEOMETRY' && (detail === 'profile relief component leaves the selected cap or target material'
    || detail === 'profile relief exact containment leaves the selected cap or target material'))
    return { title: 'Text relief extends outside the selected face',
      hint: "Adjust Baseline X and Baseline Y, or reduce Em size, so every text stroke stays inside the selected face's remaining material.",
      detail, ...extra };
  if (code === 'INPUT' && detail === 'angle must be a number of degrees, not 0, below 45 in size')
    return { ...DRAFT_ANGLE_HELP, detail, ...extra };
  // Preserve the measured strict limit; rounded guidance can recommend a refused wall.
  const shellLimit = code === 'PARAMETER' ? /^a wall of (\d+(?:\.\d+)?(?:e[+-]?\d+)?) mm leaves no hollow at ([^\r\n;]+); use a wall less than (\d+(?:\.\d+)?(?:e[+-]?\d+)?) mm$/i.exec(detail) : null;
  if (shellLimit && [shellLimit[1], shellLimit[3]].every(value => Number.isFinite(Number(value)) && Number(value) > 0)
    && Number(shellLimit[1]) >= Number(shellLimit[3])) return {
    title: 'The wall is too thick', hint: `Enter Wall less than ${shellLimit[3]} mm to keep the selected face open.`, detail, ...extra,
  };
  // Preserve the native face identity without guessing its owning feature or generalizing its limit.
  const shellFace = code === 'SHELL_FACE_KIND' ? /^\[SHELL_FACE_KIND\] (?:shell: )?face (\S+) is not an untrimmed patch, a plane or a cylinder beside a sharp edge: shelling it is not supported yet$/.exec(detail) : null;
  if (shellFace?.[0] === detail) return {
    title: 'Shell does not support this face',
    hint: `Shell cannot offset face ${shellFace[1]} in this configuration. This is not a Wall thickness error. Cancel Shell, then try another source or Shell before the finishing feature; check the new preview.`,
    detail, ...extra,
  };
  const unmatched = /^the surfaces do not close: (\d+ edges?) meet no other surface \((surfaces? [\d, ]+)\)$/.exec(detail);
  if (unmatched) return { title: 'Sew leaves unmatched edges',
    hint: `${unmatched[1]} could not be matched on ${unmatched[2]} in the listed source order. Check the gap and the tolerance.`,
    detail, ...extra };
  if (codes.has('SHELL_REGIONS_SHARP')) {
    const location = /\(at ((?:-?\d+(?:\.\d+)?(?:e[+-]?\d+)?)(?:, -?\d+(?:\.\d+)?(?:e[+-]?\d+)?){2})\): shelling there is not supported yet/i.exec(detail)?.[1];
    return { title: 'Shell cannot cross this sharp edge',
      hint: location ? `Two smooth regions meet at a sharp edge near ${location} mm. Shell does not support this junction.`
        : 'Two smooth regions meet at a sharp edge. Shell does not support this junction.',
      detail, ...extra };
  }
  for (const rule of rules) if (matches(rule, codes, message)) return { title: rule.title, hint: rule.hint, detail, ...extra };
  return { title: 'The kernel could not build this', hint: 'Undo the last change, or adjust the values and try again.', detail, ...extra };
}
/** What was thrown, as friendly(): its message and, when it has one, its code (the kernel's errors carry a string `code`). */
export function friendlyCause(cause: unknown): FriendlyError {
  if (!(cause instanceof Error)) return friendly(String(cause));
  const { code, feature, details } = cause as Error & { code?: unknown; feature?: unknown; details?: Record<string, unknown> };
  const error = friendly(cause.message, typeof code === 'string' ? code : undefined);
  if (code === 'BAD_REFERENCE' && details?.field === 'insetMM' && typeof details.linkedInsetFeature === 'string')
    error.linkedInsetFeature = details.linkedInsetFeature;
  return typeof feature === 'string' && feature ? { ...error, feature } : error;
}
