import assert from 'node:assert/strict';
import test from 'node:test';
import { starterDoc } from '../src/engine/doc';
import { drawingInputs } from '../src/chat/drawing';
import { autoLayout } from '../src/drawing/layout';
import { issueContext } from '../src/drawing/issues';
import { defaultDrawing, readDrawing } from '../src/drawing/types';
import { forSheet, mergeSheet } from '../src/drawing/sheets';
import { acceptAll, applySuggestion, toleranceSuggestions } from '../src/drawing/tolerance';

test('position suggestion reserves frame identities on other sheets', () => {
 const input = drawingInputs({...starterDoc(), drawing: defaultDrawing()});
 assert.notEqual(typeof input,'string'); if(typeof input==='string') return;
 const settings = {...autoLayout(input).settings,tolerancing:'geometric' as const};
 const first=toleranceSuggestions(issueContext({...input,settings})).find(s=>s.change.kind==='frame');
 assert.ok(first); if(first.change.kind!=='frame')return;
 const originalFrame=first.change.frame;
 const held={id:originalFrame.id,view:'right' as const,place:[10,10] as [number,number],characteristic:'flatness' as const,value:0.07,datums:[]};
 const whole={...settings,frames:[held],sheets:[{id:'S2',views:['right']}]};
 const local=forSheet(whole,0);
 const proposal=toleranceSuggestions(issueContext({...input,settings:local})).find(s=>s.change.kind==='frame'&&s.change.frame.dim===originalFrame.dim);
 assert.ok(proposal); if(proposal.change.kind!=='frame')return;
 const merged=mergeSheet(whole,0,applySuggestion(local,proposal));
 const read=readDrawing(merged);
 console.log('FRAME_IDENTITY',JSON.stringify({held,offered:proposal.change.frame,merged:merged.frames,read:read.frames}));
 assert.deepEqual(read.frames?.find(f=>f.id===held.id),held);
 assert.equal(read.frames?.length,2,'native normalization must retain both the original and accepted frame');
 assert.notEqual(proposal.change.frame.id,held.id);
 assert.equal(proposal.change.frame.dim,originalFrame.dim);
 assert.equal(read.sheetContext,undefined);
 assert.deepEqual(whole.frames,[held]);
 const reserved={...whole,frames:[held,{...held,id:held.id+'-2',value:0.08}]};
 const scoped=forSheet(reserved,0);
 const more=toleranceSuggestions(issueContext({...input,settings:scoped})).find(s=>s.change.kind==='frame'&&s.change.frame.dim===originalFrame.dim);
 assert.ok(more);if(more.change.kind!=='frame')return;
 assert.equal(more.change.frame.id,held.id+'-3');
 const all=acceptAll({...input,settings:scoped}).settings;
 const together=readDrawing(mergeSheet(reserved,0,all));
 assert.deepEqual(together.frames?.slice(0,2),reserved.frames);
 assert.equal(together.frames?.length,3);
 assert.equal(together.frames?.[2].dim,originalFrame.dim);
 assert.ok(together.dimensions.some(d=>d.basic));
 const single=toleranceSuggestions(issueContext({...input,settings})).find(s=>s.change.kind==='frame');
 assert.deepEqual(single,first);
 const duplicate={...settings,frames:[held,{...held,value:0.09}]};
 const duplicateProposal=toleranceSuggestions(issueContext({...input,settings:duplicate})).find(s=>s.change.kind==='frame');
 assert.ok(duplicateProposal);
 assert.deepEqual(applySuggestion(duplicate,duplicateProposal).frames?.slice(0,2),duplicate.frames);
});
