import { sidesOf, withIds } from '@barocss/cad-model/sketch/entityIds';
import type { SketchShape, SketchState } from '@barocss/cad-model/sketch/types';

const shapesOf = (s: SketchState) => [...(s.shape ? [s.shape] : []), ...(s.done ?? [])];
const idsOf = (s: SketchShape) => [...(s.ids ?? []), ...(s.kind === 'polygon' ? s.circleIds ?? [] : [])].filter(Boolean);
/** Clear deletes identity as well as geometry. This reservation belongs only to this undoable draft. */
export function clearProfileIdentity(s: SketchState): SketchState {
  return { ...s, shape: null, done: [], mainIds: undefined, positional: undefined,
    band: undefined, bandPicks: undefined, activeOutlineIndex: undefined, picked: [], editDim: null,
    clearedSideIds: [...new Set([...(s.clearedSideIds ?? []), ...shapesOf(s).flatMap(idsOf)])] };
}
/** Normalize before joining/Finish, including IDs generated by Trim since Clear. Never mutate draft snapshots. */
export function prepareClearedProfile(s: SketchState): SketchState {
  if (s.clearedSideIds === undefined) return s;
  const shapes = shapesOf(s), retired = new Set(s.clearedSideIds), current = shapes.flatMap(idsOf);
  if (new Set(current).size !== current.length) throw new Error('The redrawn profile has duplicate side identities. Undo Clear or redraw the profile.');
  let maximum = 0;
  for (const id of [...retired, ...current]) {
    const match = /^e([1-9]\d*)$/.exec(id), value = match ? Number(match[1]) : NaN;
    if (!Number.isSafeInteger(value)) throw new Error('The cleared profile has an unsupported side identity. Undo Clear to retain the original profile.');
    maximum = Math.max(maximum, value);
  }
  const budget = shapes.reduce((n, shape) => n + sidesOf(shape) + (shape.kind === 'polygon' ? shape.circles?.length ?? 0 : 0), 0);
  if (!Number.isSafeInteger(maximum + current.length + budget + 1)) throw new Error('No safe side identities remain for this redraw. Undo Clear to retain the original profile.');
  let next = maximum + 1;
  const remap = (id: string) => retired.has(id) ? `e${next++}` : id;
  const changed = shapes.map(shape => {
    if (!idsOf(shape).some(id => retired.has(id))) return shape;
    return { ...shape, ...(shape.ids ? { ids: shape.ids.map(remap) } : {}),
      ...(shape.kind === 'polygon' && shape.circleIds ? { circleIds: shape.circleIds.map(remap) } : {}) } as SketchShape;
  });
  const assigned = withIds(changed, next);
  return { ...s, shape: s.shape ? assigned[0] : null, done: s.shape ? assigned.slice(1) : assigned };
}
