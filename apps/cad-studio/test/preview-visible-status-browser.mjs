import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createFlow } from './flow-helper.mjs';
const pins = ['apps/cad-studio/src/app/previewStatus.ts', 'apps/cad-studio/src/App.tsx', 'apps/cad-studio/src/layout/PreviewSection.tsx', 'apps/cad-studio/src/layout/DockSection.tsx', 'apps/cad-studio/src/viewport/PrintPanel.tsx'];
const f = await createFlow({ name: 'preview-visible-status', output: process.argv[2], envFrozen: 'PREVIEW_STATUS_FROZEN', initialFiles: pins, requiredFrozen: pins,
  qualification: 'Collapsed Print and annotation states describe actual visible results without changing preview computation.', limits: ['Two desktop widths; display-only Print, ordinary drawing note/dimension. CNC/other device workflows and assistive technologies not run.'] });
const seed = JSON.parse(await readFile('apps/cad-studio/test/fixtures/bracket.bcad', 'utf8'));
const drawing = { sheet: 'A3', projection: 'third', hidden: true, scale: 2, views: ['front', 'top', 'right'], dimensions: [], notes: [{ id: 'note', text: 'SHEET ONLY', at: [80, 75] }] };
const button = (name, scope = f.page) => scope.getByRole('button', { name, exact: true });
const section = () => f.page.locator('.dock-section[aria-label="Preview & analysis"]');
const print = () => f.page.getByLabel('Print layers', { exact: true });
const mode = name => f.page.locator('.mode').getByRole('button', { name, exact: true }).click();
const select = name => f.page.getByRole('radio', { name: 'Preview: ' + name, exact: true }).click();
const readyPrint = () => f.page.waitForFunction(() => window.__studioPrint().stage === 'ready' && !!window.__studioPrint().display, null, { timeout: 60000 });
const open = async doc => { await f.openFile({ name: 'preview-status.bcad', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(doc)) }, doc.nodes.length); await f.page.waitForFunction(n => window.__studioDoc.drawing?.dimensions?.length === n, doc.drawing.dimensions.length); assert.deepEqual(await f.doc(), doc); return f.doc(); };
await f.run(async () => {
  for (const width of [1024, 1440]) {
    f.phase = `${width} sheet-only annotation count`;
    await f.newPage(); await f.page.setViewportSize({ width, height: width === 1024 ? 800 : 900 });
    await open({ ...seed, drawing });
    await f.page.getByLabel('3D annotations', { exact: true }).check();
    await section().getByText('0 annotations on the model · 1 only on the sheet', { exact: true }).waitFor();
    const end = x => ({ edge: 'n1.side0|n1.top', at: 'end', near: [x, 0, 6] });
    let annotated = { ...seed, drawing: { ...drawing, dimensions: [{ id: 'width', kind: 'linear', view: 'front', a: end(0), b: end(30), orient: 'horizontal', place: [15, 13] }] } };
    annotated = await open(annotated);
    await f.page.waitForFunction(() => window.__studioPmi().items?.length === 1);
    await section().getByText('1 annotation on the model · 1 only on the sheet', { exact: true }).waitFor();
    f.phase = `${width} collapsed Print and Drawing suspension`;
    await select('Print'); await readyPrint();
    await button('Collapse Preview & analysis').click();
    await section().getByText('Print · Ready', { exact: true }).waitFor();
    await section().getByText('Close the print or CNC preview to show the 3D annotations.', { exact: true }).waitFor();
    await f.same(annotated);
    await mode('Drawing');
    await f.page.locator('svg[aria-label="Drawing sheet"]').waitFor();
    await section().getByText('Print · Model only', { exact: true }).waitFor();
    await section().getByText(/3D annotations are shown in Model view/).waitFor();
    await f.snapshot(`${width}-drawing-collapsed`);
    await mode('Model'); await readyPrint();
    await button('Expand Preview & analysis').click();
    assert.equal(await section().getByText('Print · Ready', { exact: true }).count(), 0);
    await select('None'); await f.page.waitForFunction(() => window.__studioPmi().items?.length === 1);
    assert.equal(await f.page.getByLabel('3D annotations', { exact: true }).isChecked(), true);
    await select('Print'); await readyPrint();
    const count = await f.page.evaluate(() => window.__studioPrint().display.summary.count);
    await button('Collapse Preview & analysis').click();
    await button('New part').click(); await f.page.waitForFunction(() => window.__studioDoc.nodes.length === 0);
    await section().getByText('Print · No solid', { exact: true }).waitFor();
    await button('Expand Preview & analysis').click();
    await print().getByText('No visible solid mesh to preview.', { exact: true }).waitFor();
    assert.equal(await print().getByLabel('Print layer', { exact: true }).isDisabled(), true);
    assert.equal(await print().getByLabel('Selected print layer').count(), 0);
    assert.equal(await print().locator('.legend-chips').count(), 0);
    await print().getByText('NOT FOR PRODUCTION', { exact: true }).waitFor();
    await f.snapshot(`${width}-empty-print`);
    await f.undo(); await f.same(annotated); await readyPrint();
    assert.equal(await f.page.evaluate(() => window.__studioPrint().display.summary.count), count);
    assert.equal(await print().locator('.legend-chips').count(), 1);
    await f.redo(); await f.page.waitForFunction(() => window.__studioDoc.nodes.length === 0);
    await print().getByText('No visible solid mesh to preview.', { exact: true }).waitFor();
    assert.equal(await print().locator('.legend-chips').count(), 0);
    await print().getByText('NOT FOR PRODUCTION', { exact: true }).waitFor();
    await f.undo(); await f.same(annotated); await select('None');
    await f.page.waitForFunction(() => window.__studioPmi().items?.length === 1);
    await f.same(annotated);
  }
});
